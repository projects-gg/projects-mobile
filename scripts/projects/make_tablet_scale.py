"""TABLET-M: caps upstream's portrait-sdp / portrait-ssp scaling on large windows held upright.

The two libraries (PojavLauncherTeam/portrait-sdp, portrait-ssp) scale every _Nsdp / _Nssp by the smallest width in
portrait (sw/300): a phone's 1.2-1.4 times, but 2.0-3.6 times on a tablet held upright (the theme's text 24 sp and more,
the download strip twice as tall). This writes, for each of the libraries' buckets from sw450dp-port up, the names the
app uses at the sw420dp-port scale (1.4), so a tablet upright looks like a large phone; landscape keeps the base values.

    python scripts/projects/make_tablet_scale.py app_pojavlauncher/src/main
"""
import os
import re
import sys

main = sys.argv[1]
res = os.path.join(main, "res")
names = set()
for base in (res, os.path.join(main, "java")):
    for dirpath, _, files in os.walk(base):
        if "values-sw" in dirpath and "projects_tablet_scale" in "".join(files):
            continue
        for f in files:
            if not f.endswith((".xml", ".java")) or f == "projects_tablet_scale.xml":
                continue
            with open(os.path.join(dirpath, f), encoding="utf-8", errors="ignore") as fh:
                names.update(re.findall(r"_(\d+)(sdp|ssp)\b", fh.read()))

BUCKETS = [450, 480, 510, 540, 570, 600, 630, 660, 690, 720, 750, 780, 810, 840, 870, 900, 930, 960, 990, 1020, 1050, 1080]
SCALE = 420 / 300  # the sw420dp-port bucket's scale


def fmt(v):
    return ("%.2f" % v).rstrip("0").rstrip(".")


entries = sorted(names, key=lambda n: (n[1], int(n[0])))
for b in BUCKETS:
    d = os.path.join(res, "values-sw%ddp-port" % b)
    os.makedirs(d, exist_ok=True)
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- TABLET-M (generated by scripts/projects/make_tablet_scale.py, do not edit): a window at least %ddp in its smallest width,"
        % b,
        "     held upright, keeps the sw420dp-port scale (1.4) of upstream's portrait-sdp / portrait-ssp values the app uses,",
        "     instead of %s times: a tablet upright looks like a large phone. -->" % fmt(b / 300),
        "<resources>",
    ]
    for n, kind in entries:
        unit = "dp" if kind == "sdp" else "sp"
        lines.append('    <dimen name="_%s%s">%s%s</dimen>' % (n, kind, fmt(int(n) * SCALE), unit))
    lines.append("</resources>")
    with open(os.path.join(d, "projects_tablet_scale.xml"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
print("%d names in %d buckets" % (len(entries), len(BUCKETS)))
